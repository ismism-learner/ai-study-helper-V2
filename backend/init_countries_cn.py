def init_countries_with_chinese():
    db = SessionLocal()
    try:
        db.query(Country).delete()
        db.commit()
        
        count = 0
        for country_data in COUNTRIES_CN:
            country = Country(
                code=country_data["code"],
                name=country_data["name"],
                region=country_data["region"],
                continent=country_data["continent"],
                geojson_properties={"coordinates": country_data["coordinates"]}
            )
            db.add(country)
            count += 1
        
        db.commit()
        print(f"成功初始化 {count} 个国家（含中文翻译）")
        
    except Exception as e:
        print(f"初始化失败: {e}")
        db.rollback()
        raise
    finally:
        db.close()

def init_historical_periods():
    from app.models import TimePeriod
    db = SessionLocal()
    try:
        db.query(TimePeriod).delete()
        db.commit()
        
        count = 0
        for country_code, periods in HISTORICAL_PERIODS.items():
            country = db.query(Country).filter(Country.code == country_code).first()
            if not country:
                print(f"未找到国家: {country_code}")
                continue
            
            for period_data in periods:
                period = TimePeriod(
                    name=period_data["name"],
                    start_year=period_data["start_year"],
                    end_year=period_data["end_year"],
                    country_id=country.id
                )
                db.add(period)
                count += 1
        
        db.commit()
        print(f"成功初始化 {count} 个历史时期")
        
    except Exception as e:
        print(f"初始化历史时期失败: {e}")
        db.rollback()
        raise
    finally:
        db.close()

if __name__ == "__main__":
    init_countries_with_chinese()
    init_historical_periods()
