def init_countries():
    """初始化国家数据"""
    try:
        countries_data = download_countries_data()
        coordinates_map = get_country_coordinates()
        
        db = next(get_db())
        
        # 清空现有数据
        db.query(Country).delete()
        db.commit()
        
        # 插入新数据
        count = 0
        for country in countries_data:
            alpha2 = country.get('alpha-2', '')
            coordinates = coordinates_map.get(alpha2, [0, 0])
            
            country_obj = Country(
                id=alpha2.lower(),
                name=country.get('name', ''),
                code=alpha2,
                region=country.get('region', ''),
                continent=country.get('region', ''),
                geojson_properties={
                    "coordinates": coordinates
                }
            )
            db.add(country_obj)
            count += 1
        
        db.commit()
        print(f"成功初始化 {count} 个国家")
        
    except Exception as e:
        print(f"初始化失败: {e}")
        raise

if __name__ == "__main__":
    init_countries()
